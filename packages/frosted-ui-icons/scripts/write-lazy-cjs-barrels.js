const fs = require('fs');
const path = require('path');

const PACKAGE_ROOT = path.join(__dirname, '..');
const SRC = path.join(PACKAGE_ROOT, 'src');
const CJS = path.join(PACKAGE_ROOT, 'dist', 'cjs');

const RE_EXPORT = /^export \{ default as (\w+) \} from '(\.\/[\w/-]+)';$/;
const STAR_EXPORT = /^export \* from '(\.\/[\w/-]+)';$/;

/**
 * Reads one of the generated barrels and returns `[{ name, request }]`, where
 * `request` is the specifier to require *relative to the barrel being emitted*.
 * Star re-exports are flattened so the root barrel can reach a pictogram module
 * directly instead of pulling in the pictograms barrel to get at one component.
 *
 * Anything that is not a default re-export, a star re-export or blank is a shape
 * the generator has not seen before: we throw rather than silently drop exports,
 * because a missing export here is a break that only shows up in a consumer.
 */
function readBarrel(barrelPath, requestPrefix = './') {
  const exports = [];

  fs.readFileSync(barrelPath, 'utf8')
    .split('\n')
    .forEach((line, index) => {
      if (line.trim() === '') return;

      const reExport = line.match(RE_EXPORT);
      if (reExport) {
        const [, name, target] = reExport;
        exports.push({ name, request: requestPrefix + target.slice('./'.length) });
        return;
      }

      const starExport = line.match(STAR_EXPORT);
      if (starExport) {
        const nested = starExport[1].slice('./'.length);
        exports.push(
          ...readBarrel(path.join(path.dirname(barrelPath), nested, 'index.tsx'), `${requestPrefix + nested}/`),
        );
        return;
      }

      throw new Error(
        `${path.relative(PACKAGE_ROOT, barrelPath)}:${index + 1}: unrecognized export, ` +
          `update ${path.basename(__filename)} to handle it:\n  ${line}`,
      );
    });

  return exports;
}

const PREAMBLE = `'use strict';
// Generated by scripts/${path.basename(__filename)} — do not edit.
//
// tsc compiles each re-export in the barrel to an eager \`require()\`, so pulling a
// single icon out of the CJS build loaded every module in the package. ESM
// consumers are unaffected (bundlers tree-shake \`dist/esm\`), but CommonJS has no
// tree-shaking, so instead we define every export as a getter that requires its
// module on first access and then caches the result in place.
//
// The \`require()\` calls are literal rather than built from a variable so that
// bundlers reading the \`main\` field can still resolve them statically.
Object.defineProperty(exports, '__esModule', { value: true });

function d(name, load) {
  Object.defineProperty(exports, name, {
    enumerable: true,
    configurable: true,
    get: function () {
      var mod = load();
      var value = mod && mod.__esModule ? mod.default : mod;
      Object.defineProperty(exports, name, { enumerable: true, configurable: true, value: value });
      return value;
    },
  });
}
`;

function writeLazyBarrel(sourceBarrel, outputBarrel) {
  if (!fs.existsSync(outputBarrel)) {
    throw new Error(`${path.relative(PACKAGE_ROOT, outputBarrel)} is missing; run the TypeScript build first.`);
  }

  const exports = readBarrel(sourceBarrel);
  const names = new Set(exports.map((e) => e.name));
  if (names.size !== exports.length) {
    throw new Error(`${path.relative(PACKAGE_ROOT, sourceBarrel)} declares the same export twice.`);
  }

  const body = exports.map((e) => `d('${e.name}', function () { return require('${e.request}'); });`).join('\n');
  fs.writeFileSync(outputBarrel, `${PREAMBLE}\n${body}\n`);

  return exports;
}

const rootExports = writeLazyBarrel(path.join(SRC, 'index.tsx'), path.join(CJS, 'index.js'));
const pictogramExports = writeLazyBarrel(
  path.join(SRC, 'pictograms', 'index.tsx'),
  path.join(CJS, 'pictograms', 'index.js'),
);

/**
 * Loads what we just emitted so a bad barrel fails this build instead of a
 * consumer's app: every source export has to be present and resolve to a
 * component, and requiring the barrel must not pull in the icon modules.
 */
function verify(barrelPath, expected, label) {
  const modulesBefore = Object.keys(require.cache).length;
  const barrel = require(barrelPath);
  const loadedByRequiringBarrel = Object.keys(require.cache).length - modulesBefore - 1;

  const actual = Object.keys(barrel);
  const expectedNames = expected.map((e) => e.name);
  const missing = expectedNames.filter((name) => !actual.includes(name));
  if (missing.length || actual.length !== expectedNames.length) {
    throw new Error(
      `${label}: emitted ${actual.length} exports, expected ${expectedNames.length}` +
        (missing.length ? `; missing e.g. ${missing[0]}` : '') +
        '.',
    );
  }

  if (loadedByRequiringBarrel !== 0) {
    throw new Error(`${label}: requiring the barrel eagerly loaded ${loadedByRequiringBarrel} module(s).`);
  }

  const probe = expectedNames[expectedNames.length - 1];
  if (typeof barrel[probe] !== 'function') {
    throw new Error(`${label}: export ${probe} did not resolve to a component.`);
  }

  return actual.length;
}

const rootCount = verify(path.join(CJS, 'index.js'), rootExports, 'dist/cjs/index.js');
verify(path.join(CJS, 'pictograms', 'index.js'), pictogramExports, 'dist/cjs/pictograms/index.js');

console.log(
  `Rewrote CJS barrels with lazy getters: ${rootCount} exports ` +
    `(${pictogramExports.length} pictograms) now resolve on demand.`,
);
